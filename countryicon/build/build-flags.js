#!/usr/bin/env node
// Reads every SVG in countryicon/src/flags/, and generates:
//   - flag-countries.generated.ts  (FlagCountry union type, FLAG_COUNTRIES list, FLAG_LABELS)
//   - flags.web.generated.tsx      (per-flag inner JSX, plain DOM svg tags)
//   - flags.native.generated.tsx   (per-flag inner JSX, react-native-svg tags)
//
// Every source SVG (verified across all 260) uses only rect/g/path/defs/clipPath
// and only clip-path/d/fill/height/id/viewBox/width/xmlns attributes — no style,
// transform, mask, gradient, text, or <use>. That narrow, uniform vocabulary is
// exactly why a small hand-rolled transform is safe here instead of pulling in
// a full SVGR/svgo dependency.
//
// Every source file reuses the SAME literal id ("clip0_748_47") for its
// clipPath — harmless in isolation, but guaranteed to collide (silently
// corrupting every other flag's crop shape) the moment two <Flag>s render on
// the same page. Fixed by suffixing every id with that flag's own slug before
// emitting it, and rewriting url(#id) refs to match.

const fs = require("fs");
const path = require("path");

const FLAGS_DIR = path.join(__dirname, "..", "src", "flags");
const OUT_DIR = path.join(__dirname, "..", "src");

const files = fs
  .readdirSync(FLAGS_DIR)
  .filter((f) => f.endsWith(".svg"))
  .sort();

function slugToPascal(slug) {
  return slug
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

function slugToLabel(slug) {
  return slug
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

// Extracts the markup between the outer <svg ...> and </svg>, drops the
// leading rgb(250,250,250) background square every source file has (Figma's
// own export chrome, not part of the flag), uniquifies every id in that
// file to <id>-<slug>, and rewrites url(#id) refs to match.
function extractInnerMarkup(svgSource, slug) {
  let inner = svgSource.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");

  // Always the literal first element, exactly once — never confuse with the
  // <clipPath>'s own <rect>, which defines the actual circular crop and must
  // stay (some flags' clip rect also happens to be exactly 24x24, but it's
  // fill="white" and lives inside <defs>, not this leading fill="#FAFAFA" one).
  inner = inner.replace(/^\s*<rect width="24" height="24" fill="#FAFAFA"\/>\s*/, "");

  const ids = new Set();
  for (const m of inner.matchAll(/\bid="([^"]+)"/g)) ids.add(m[1]);

  let out = inner;
  for (const id of ids) {
    const unique = `${id}-${slug}`;
    out = out
      .split(`id="${id}"`).join(`id="${unique}"`)
      .split(`url(#${id})`).join(`url(#${unique})`);
  }
  return out.trim();
}

function toWebJsx(markup) {
  // Only rename attributes — every tag name (rect/g/path/defs/clipPath) is
  // already a valid lowercase DOM element name, so no tag rewriting needed.
  return markup.replace(/\bclip-path=/g, "clipPath=");
}

const NATIVE_TAG_MAP = { rect: "Rect", g: "G", path: "Path", defs: "Defs", clipPath: "ClipPath" };

function toNativeJsx(webJsx) {
  let out = webJsx;
  for (const [from, to] of Object.entries(NATIVE_TAG_MAP)) {
    out = out.replace(new RegExp(`<${from}(?=[\\s/>])`, "g"), `<${to}`).replace(new RegExp(`</${from}>`, "g"), `</${to}>`);
  }
  return out;
}

const entries = []; // { slug, pascal, label, nodeId, webJsx, nativeJsx }

const manifestPath = path.join(FLAGS_DIR, "manifest.json");
const rawManifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const byFilename = new Map(rawManifest.flags.map((f) => [f.filename, f]));

for (const file of files) {
  const slug = file.replace(/\.svg$/, "");
  const svgSource = fs.readFileSync(path.join(FLAGS_DIR, file), "utf8");
  const innerMarkup = extractInnerMarkup(svgSource, slug);
  const webJsx = toWebJsx(innerMarkup);
  const nativeJsx = toNativeJsx(webJsx);
  const meta = byFilename.get(file);

  entries.push({
    slug,
    pascal: slugToPascal(slug),
    label: slugToLabel(slug),
    nodeId: meta ? meta.nodeId : null,
    webJsx,
    nativeJsx,
  });
}

// --- flag-countries.generated.ts ---
const countriesFile = `// GENERATED by build/build-flags.js — do not edit by hand.
export type FlagCountry =
${entries.map((e) => `  | "${e.slug}"`).join("\n")};

export const FLAG_COUNTRIES: FlagCountry[] = [
${entries.map((e) => `  "${e.slug}",`).join("\n")}
];

// Straight Title Case of the slug — good enough for a picker label; a few
// entries (e.g. "Nato") read better as an acronym than this produces, but
// that's a cosmetic gap not worth hand-listing exceptions for 260 entries.
export const FLAG_LABELS: Record<FlagCountry, string> = {
${entries.map((e) => `  "${e.slug}": "${e.label}",`).join("\n")}
};
`;
fs.writeFileSync(path.join(OUT_DIR, "flag-countries.generated.ts"), countriesFile);

// --- flags.web.generated.tsx ---
const webFile = `// GENERATED by build/build-flags.js — do not edit by hand.
import type { FlagCountry } from "./flag-countries.generated";

export const FLAG_CONTENT: Record<FlagCountry, () => React.JSX.Element> = {
${entries.map((e) => `  "${e.slug}": () => (\n    <>\n${e.webJsx.split("\n").map((l) => "      " + l).join("\n")}\n    </>\n  ),`).join("\n")}
};
`;
fs.writeFileSync(path.join(OUT_DIR, "flags.web.generated.tsx"), webFile);

// --- flags.native.generated.tsx ---
const nativeFile = `// GENERATED by build/build-flags.js — do not edit by hand.
import * as React from "react";
import { Rect, G, Path, Defs, ClipPath } from "react-native-svg";
import type { FlagCountry } from "./flag-countries.generated";

export const FLAG_CONTENT: Record<FlagCountry, () => React.JSX.Element> = {
${entries.map((e) => `  "${e.slug}": () => (\n    <React.Fragment>\n${e.nativeJsx.split("\n").map((l) => "      " + l).join("\n")}\n    </React.Fragment>\n  ),`).join("\n")}
};
`;
fs.writeFileSync(path.join(OUT_DIR, "flags.native.generated.tsx"), nativeFile);

console.log(`Generated ${entries.length} flags -> flag-countries.generated.ts, flags.web.generated.tsx, flags.native.generated.tsx`);
